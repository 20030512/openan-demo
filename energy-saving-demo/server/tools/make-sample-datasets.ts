/**
 * Builds server/src/sample-datasets.ts from the colleague's price samples in sample/test-prices (the energy-saving-uc
 * project). Every valid .xlsx there becomes one built-in test dataset: its price days, its slot length and the charge and
 * discharge durations the team's expected results use (300 and 240 minutes).
 * Run from server/: npx tsx tools/make-sample-datasets.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import ExcelJS from 'exceljs'

const dir = fileURLToPath(new URL('../../sample/test-prices/', import.meta.url))
const out = fileURLToPath(new URL('../src/sample-datasets.ts', import.meta.url))

/** "| A1_tiered-tariff_G0.5.xlsx | 30 min | Scenario | What it tests | ..." -> file -> [scenario, what it tests] */
const notes = new Map<string, [string, string]>()
for (const line of readFileSync(join(dir, 'README.md'), 'utf8').split(/\r?\n/)) {
  const c = line.split('|').map((x) => x.trim())
  if (c.length > 5 && /\.xlsx$/.test(c[1])) notes.set(c[1], [c[3], c[4]])
}

const expected = new Set(
  readFileSync(join(dir, 'expected-results.csv'), 'utf8')
    .split(/\r?\n/)
    .slice(1)
    .map((l) => l.split(',')[0])
    .filter((f) => f.endsWith('.xlsx')),
)

const sets: unknown[] = []
for (const file of [...expected].sort((a, b) => a.localeCompare(b, 'en', { numeric: true }))) {
  const wb = new ExcelJS.Workbook()
  await wb.xlsx.readFile(join(dir, file))
  const days = new Map<string, { slot: string; price: number }[]>()
  wb.worksheets[0].eachRow((row, i) => {
    if (i === 1) return
    const v = row.getCell(1).value
    const date = v instanceof Date ? v.toISOString().slice(0, 10) : String(v).slice(0, 10)
    days.set(date, [...(days.get(date) ?? []), { slot: String(row.getCell(2).value), price: Number(row.getCell(3).value) }])
  })
  const g = Number(/_G(\d+(?:\.\d+)?)\./.exec(file)?.[1])
  const [scenario = '', tests = ''] = notes.get(file) ?? []
  const prices = [...days].sort(([a], [b]) => a.localeCompare(b)).map(([, s]) => s.sort((x, y) => x.slot.localeCompare(y.slot)).map((x) => x.price))
  sets.push({
    name: file.replace(/_G[\d.]+\.xlsx$/, '').replace(/^([A-Z]\d+)_/, '$1 ').slice(0, 64),
    description: `${scenario}. ${tests}`.slice(0, 200),
    granularity: g,
    days: prices,
  })
}

writeFileSync(
  out,
  `// Generated by tools/make-sample-datasets.ts from sample/test-prices (the colleague's energy-saving-uc samples). Do not edit.
export interface SampleDataset { name: string; description: string; granularity: number; days: number[][] }
/** Charge and discharge minutes the team's expected-results.csv uses. */
export const SAMPLE_CHARGE_MIN = 300
export const SAMPLE_DISCHARGE_MIN = 240
export const SAMPLE_DATASETS: SampleDataset[] = ${JSON.stringify(sets)}
`,
)
console.log(`${sets.length} datasets written`)
